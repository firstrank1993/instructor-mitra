// Main Sidebar Component
const Sidebar = ({ isAdmin = false, isOpen = true, onClose }) => {
  const navigate = useNavigate();
  const { userData, clearUser } = useAuthStore();

  const handleSignOut = async () => {
    await signOutUser();
    clearUser();
    navigate('/login');
  };

  const instructorLinks = [
    { to: '/dashboard', icon: <DashboardIcon />, label: 'Dashboard', end: true },
    { to: '/dashboard/batches', icon: <BatchIcon />, label: 'Batches' },
    { to: '/dashboard/trainees', icon: <TraineeIcon />, label: 'Trainees' },
    { to: '/dashboard/marks', icon: <MarksIcon />, label: 'Marks Entry' },
    { to: '/dashboard/reports', icon: <ReportIcon />, label: 'Reports' },
    { to: '/dashboard/profile', icon: <ProfileIcon />, label: 'Profile' },
  ];

  const adminLinks = [
    { to: '/admin', icon: <DashboardIcon />, label: 'Dashboard', end: true },
    { to: '/admin/users', icon: <UsersIcon />, label: 'User Management' },
    { to: '/admin/trades', icon: <TradeIcon />, label: 'Trade Management' },
    { to: '/admin/assessment', icon: <AdminIcon />, label: 'Assessment Setup' },
  ];

  const links = isAdmin ? adminLinks : instructorLinks;

  return (
    <>
      {/* Mobile Overlay */}
      {isOpen && (
        <div
          className="fixed inset-0 bg-black bg-opacity-50 z-20 lg:hidden"
          onClick={onClose}
        />
      )}

      {/* Sidebar */}
      <aside className={`
        fixed top-0 left-0 h-full w-64 bg-white border-r border-gray-200 z-30
        flex flex-col transition-transform duration-300 ease-in-out
        ${isOpen ? 'translate-x-0' : '-translate-x-full'}
        lg:translate-x-0 lg:static lg:z-auto
      `}>

        {/* Logo */}
        <div className="flex items-center gap-3 px-6 py-5 border-b border-gray-100">
          <div className="w-9 h-9 bg-blue-600 rounded-xl flex items-center justify-center flex-shrink-0">
            <svg className="w-5 h-5 text-white" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M12 6.253v13m0-13C10.832 5.477 9.246 5 7.5 5S4.168 5.477 3 6.253v13C4.168 18.477 5.754 18 7.5 18s3.332.477 4.5 1.253m0-13C13.168 5.477 14.754 5 16.5 5c1.747 0 3.332.477 4.5 1.253v13C19.832 18.477 18.247 18 16.5 18c-1.746 0-3.332.477-4.5 1.253" />
            </svg>
          </div>
          <div>
            <h1 className="font-bold text-gray-900 text-sm">{APP_NAME}</h1>
            <p className="text-xs text-gray-500">{isAdmin ? 'Admin Panel' : 'Instructor Portal'}</p>
          </div>
        </div>

        {/* Navigation */}
        <nav className="flex-1 px-3 py-4 space-y-1 overflow-y-auto">
          {links.map((link) => (
            <NavItem
              key={link.to}
              to={link.to}
              icon={link.icon}
              label={link.label}
              end={link.end}
              onClick={onClose}
            />
          ))}
        </nav>

        {/* User Profile + Logout */}
        <div className="p-3 border-t border-gray-100">
          {/* User Info */}
          <div className="flex items-center gap-3 px-3 py-2 mb-2">
            {userData?.photoURL ? (
              <img
                src={userData.photoURL}
                alt="profile"
                className="w-8 h-8 rounded-full flex-shrink-0"
              />
            ) : (
              <div className="w-8 h-8 bg-blue-600 rounded-full flex items-center justify-center text-white text-sm font-bold flex-shrink-0">
                {userData?.displayName?.[0] || 'U'}
              </div>
            )}
            <div className="flex-1 min-w-0">
              <p className="text-sm font-medium text-gray-800 truncate">
                {userData?.displayName}
              </p>
              <p className="text-xs text-gray-500 truncate">
                {userData?.tradeName || 'Admin'}
              </p>
            </div>
          </div>

          {/* Logout Button */}
          <button
            onClick={handleSignOut}
            className="w-full flex items-center gap-3 px-4 py-2.5 rounded-xl text-sm font-medium text-red-600 hover:bg-red-50 transition-colors duration-200"
          >
            <LogoutIcon />
            <span>Sign Out</span>
          </button>
        </div>
      </aside>
    </>
  );
};

export default Sidebar;